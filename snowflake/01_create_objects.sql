-- PTFI Mine Intelligence
-- Object setup for a small, cost-aware Snowflake practice environment.

CREATE DATABASE IF NOT EXISTS PTFI_MINE_ANALYTICS;
CREATE SCHEMA IF NOT EXISTS PTFI_MINE_ANALYTICS.OPERATIONS;

CREATE WAREHOUSE IF NOT EXISTS MINE_ANALYTICS_WH
    WITH WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    INITIALLY_SUSPENDED = TRUE
    MIN_CLUSTER_COUNT = 1
    MAX_CLUSTER_COUNT = 1
    SCALING_POLICY = 'STANDARD'
    COMMENT = 'PTFI practice warehouse; auto-suspends after 60 seconds';

-- Enforce the guardrail even when the warehouse already existed.
ALTER WAREHOUSE MINE_ANALYTICS_WH SET
    WAREHOUSE_SIZE = 'X-SMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE
    MIN_CLUSTER_COUNT = 1
    MAX_CLUSTER_COUNT = 1
    SCALING_POLICY = 'STANDARD';

CREATE TABLE IF NOT EXISTS PTFI_MINE_ANALYTICS.OPERATIONS.PRODUCTION_DAILY (
    OPERATION_DATE DATE NOT NULL,
    REGION VARCHAR(80) NOT NULL,
    PIT_NAME VARCHAR(120) NOT NULL,
    MINERAL VARCHAR(40) NOT NULL,
    SHIFT VARCHAR(40) NOT NULL,
    ORE_TONNES NUMBER(18, 2) NOT NULL,
    TARGET_TONNES NUMBER(18, 2) NOT NULL,
    GRADE_PCT NUMBER(8, 3),
    OPERATING_COST_USD NUMBER(18, 2),
    LOADED_TRUCKS NUMBER(12, 0),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS PTFI_MINE_ANALYTICS.OPERATIONS.EQUIPMENT_DAILY (
    OPERATION_DATE DATE NOT NULL,
    ASSET_ID VARCHAR(40) NOT NULL,
    ASSET_TYPE VARCHAR(80) NOT NULL,
    PIT_NAME VARCHAR(120) NOT NULL,
    HOURS_AVAILABLE NUMBER(8, 2),
    HOURS_OPERATING NUMBER(8, 2),
    UPTIME_PCT NUMBER(8, 2),
    FUEL_LITERS NUMBER(18, 2),
    MAINTENANCE_STATUS VARCHAR(40),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE TABLE IF NOT EXISTS PTFI_MINE_ANALYTICS.OPERATIONS.LOGISTICS_SHIPMENTS (
    SHIPMENT_ID VARCHAR(40) NOT NULL,
    VESSEL_NAME VARCHAR(120) NOT NULL,
    MINERAL VARCHAR(40) NOT NULL,
    SOURCE_PIT VARCHAR(120) NOT NULL,
    DESTINATION_PORT VARCHAR(120) NOT NULL,
    DISPATCH_DATE DATE NOT NULL,
    ETA_DATE DATE NOT NULL,
    TONNES NUMBER(18, 2) NOT NULL,
    READINESS_PCT NUMBER(8, 2),
    STATUS VARCHAR(50),
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

COMMENT ON DATABASE PTFI_MINE_ANALYTICS IS 'PTFI mine operations and logistics query practice';
COMMENT ON SCHEMA PTFI_MINE_ANALYTICS.OPERATIONS IS 'Operational demo tables for React dashboard';
