USE DATABASE PTFI_MINE_ANALYTICS;
USE SCHEMA OPERATIONS;
USE WAREHOUSE MINE_ANALYTICS_WH;

-- 1. Daily actual versus target.
SELECT
    OPERATION_DATE,
    ROUND(SUM(ORE_TONNES), 0) AS ACTUAL_ORE_TONNES,
    ROUND(SUM(TARGET_TONNES), 0) AS TARGET_ORE_TONNES,
    ROUND(SUM(ORE_TONNES) / NULLIF(SUM(TARGET_TONNES), 0) * 100, 2) AS ATTAINMENT_PCT
FROM PRODUCTION_DAILY
GROUP BY OPERATION_DATE
ORDER BY OPERATION_DATE DESC;

-- 2. Pit contribution and production gap.
SELECT
    PIT_NAME,
    ROUND(SUM(ORE_TONNES), 0) AS ACTUAL_ORE_TONNES,
    ROUND(SUM(TARGET_TONNES), 0) AS TARGET_ORE_TONNES,
    ROUND((SUM(ORE_TONNES) - SUM(TARGET_TONNES)) / NULLIF(SUM(TARGET_TONNES), 0) * 100, 2) AS GAP_PCT
FROM PRODUCTION_DAILY
GROUP BY PIT_NAME
ORDER BY ACTUAL_ORE_TONNES DESC;

-- 3. Fleet uptime by asset type and pit.
SELECT
    ASSET_TYPE,
    PIT_NAME,
    ROUND(AVG(UPTIME_PCT), 2) AS AVG_UPTIME_PCT,
    ROUND(SUM(HOURS_OPERATING), 1) AS OPERATING_HOURS
FROM EQUIPMENT_DAILY
GROUP BY ASSET_TYPE, PIT_NAME
ORDER BY AVG_UPTIME_PCT ASC;

-- 4. Shipment readiness watchlist.
SELECT
    SHIPMENT_ID,
    VESSEL_NAME,
    SOURCE_PIT,
    DESTINATION_PORT,
    ETA_DATE,
    READINESS_PCT,
    STATUS
FROM LOGISTICS_SHIPMENTS
WHERE READINESS_PCT < 85 OR STATUS = 'Documentation Hold'
ORDER BY ETA_DATE;

-- 5. Try a CTE to compare production with fleet uptime per pit.
WITH production_by_pit AS (
    SELECT PIT_NAME, SUM(ORE_TONNES) AS ORE_TONNES
    FROM PRODUCTION_DAILY
    GROUP BY PIT_NAME
),
fleet_by_pit AS (
    SELECT PIT_NAME, AVG(UPTIME_PCT) AS UPTIME_PCT
    FROM EQUIPMENT_DAILY
    GROUP BY PIT_NAME
)
SELECT
    p.PIT_NAME,
    ROUND(p.ORE_TONNES, 0) AS ORE_TONNES,
    ROUND(f.UPTIME_PCT, 2) AS UPTIME_PCT
FROM production_by_pit p
LEFT JOIN fleet_by_pit f ON f.PIT_NAME = p.PIT_NAME
ORDER BY ORE_TONNES DESC;
